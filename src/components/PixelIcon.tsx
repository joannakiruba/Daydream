interface PixelIconProps {
  name: string
  size?: number
  color?: string
  style?: CSSProperties
}

export function PixelIcon({ name, size = 16, color = 'currentColor', style }: PixelIconProps) {
  const rects = ICONS[name] ?? ICONS.alert
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 16 16"
      width={size}
      height={size}
      fill={color}
      shapeRendering="crispEdges"
      style={{ display: 'block', flexShrink: 0, imageRendering: 'pixelated', ...style }}
    >
      {rects.map(([x, y, w, h], i) => (
        <rect key={i} x={x} y={y} width={w} height={h} />
      ))}
    </svg>
  )
}
